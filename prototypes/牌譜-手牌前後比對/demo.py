# -*- coding: utf-8 -*-
"""
demo.py
=======
用假資料跑 HandTracker，驗證「前後比對算摸打」在各種情況下對不對。
不需要鏡頭、不需要 AI 模型 —— 這裡直接手打幾份假的手牌快照餵進去。

執行： python3 demo.py
"""

import json
from hand_tracker import HandTracker, is_valid_taiwan_hand
from tiles import to_cn, hand_to_cn


def show(title, snapshots):
    """跑一段快照序列，把每一步偵測到的事件印出來。"""
    print("\n" + "=" * 56)
    print("情境：" + title)
    print("=" * 56)
    t = HandTracker("東家")
    events = []
    for i, snap in enumerate(snapshots):
        ok, note = is_valid_taiwan_hand(snap)
        ev = t.feed(snap)
        tag = "" if ok else f"  ⚠ 手牌張數異常（{note}）"
        if ev is None:
            print(f"  第{i+1}張快照 → （無變化，略過）{tag}")
        else:
            print(f"  第{i+1}張快照 → {describe(ev)}{tag}")
            events.append(ev)
    return events


def describe(ev):
    """把事件 dict 轉成人看得懂的一句話。"""
    e = ev["事件"]
    if e == "起手":
        return f"【起手】{ev['張數']} 張：{hand_to_cn(ev['牌'])}"
    if e == "摸牌":
        return f"【摸牌】摸到「{to_cn(ev['牌'])}」"
    if e == "打牌":
        return f"【打牌】打出「{to_cn(ev['牌'])}」（{ev['類型']}）"
    if e == "摸打":
        return f"【摸打】摸「{to_cn(ev['摸'])}」、打「{to_cn(ev['打'])}」（{ev['類型']}）"
    if e == "疑似吃碰槓":
        return f"【疑似碰/槓/吃】少了 {hand_to_cn(ev['少掉的牌'])} → {ev['備註']}"
    if e == "異常變化":
        return f"【異常】多 {hand_to_cn(ev['多出的牌'])}、少 {hand_to_cn(ev['少掉的牌'])}、張數變化 {ev['張數變化']} → 需人工複查"
    return str(ev)


# 一份固定的假起手牌（16 張），後面情境都從它變化
BASE = ["1m", "1m", "5p", "5p", "9t", "3m", "7p", "2t",
        "E0", "E0", "F0", "B0", "6m", "4p", "8t", "S0"]


# ---------------------------------------------------------------
# 情境 1：正常「摸到直接打」，而且鏡頭有拍到 17 張的中間狀態
#   休息16 → 摸進「中」變17 → 打掉「中」回16
# ---------------------------------------------------------------
s1 = [
    BASE,
    BASE + ["C0"],            # 摸到「中」
    BASE,                     # 把「中」打掉 → 摸到直接打
]

# ---------------------------------------------------------------
# 情境 2：正常「打手裡的牌」，鏡頭有拍到 17 張
#   摸進「九筒」→ 留著、改打手裡的「九條」
# ---------------------------------------------------------------
s2_hold = BASE + ["9p"]
s2_after = [x for x in s2_hold if x != "9t"]   # 打掉九條，留下九筒
s2 = [
    BASE,
    s2_hold,                  # 摸到「九筒」（17張）
    s2_after,                 # 打掉手裡的「九條」→ 打手裡的牌
]

# ---------------------------------------------------------------
# 情境 3：漏拍了 17 張狀態，只拍到前後兩個 16 張
#   系統只看到「少了九條、多了九筒」→ 一次判定成摸打
# ---------------------------------------------------------------
s3 = [
    BASE,
    s2_after,                 # 直接跳到打完的樣子（中間17張沒拍到）
]

# ---------------------------------------------------------------
# 情境 4：摸到直接打，但只拍到休息狀態（16→16，內容一樣）
#   側面鏡頭看不到！ → 略過，這張打出去的牌要靠俯視補
# ---------------------------------------------------------------
s4 = [
    BASE,
    BASE,                     # 完全沒變 → 側面偵測不到（摸切在河裡，俯視才看得到）
]

# ---------------------------------------------------------------
# 情境 5：碰牌 —— 手裡兩張「東」+ 別人打的東 → 吃碰槓，再打一張
#   手牌一次少掉 2 張「東」→ 系統標記疑似吃碰槓，等俯視確認
# ---------------------------------------------------------------
s5_after_pon = [x for x in BASE if x != "E0"]      # 兩張東移到吃碰槓區
s5 = [
    BASE,
    s5_after_pon,             # 少了兩張東 → 疑似碰
]

# ---------------------------------------------------------------
# 情境 6：辨識出錯 —— 突然少了 3 張又多 2 張、對不上任何樣式
#   系統標記異常、需人工複查，但不丟資料
# ---------------------------------------------------------------
s6_broken = ["1m", "1m", "5p", "5p", "9t", "3m", "7p",
             "W0", "N0", "F0", "B0", "6m", "4p", "8t"]   # 只有14張、內容亂
s6 = [
    BASE,
    s6_broken,
]


if __name__ == "__main__":
    print("台麻側面鏡頭『前後比對算摸打』邏輯驗證")
    print("（假資料，不含鏡頭與 AI 模型）")

    all_events = []
    all_events += show("1. 摸到直接打（有拍到 17 張中間狀態）", s1)
    all_events += show("2. 打手裡的牌（有拍到 17 張中間狀態）", s2)
    all_events += show("3. 漏拍 17 張，只看到前後 16 張 → 仍算得出摸打", s3)
    all_events += show("4. 摸到直接打、但只拍到休息狀態 → 側面看不到，要靠俯視", s4)
    all_events += show("5. 碰牌 → 手牌少兩張，標記疑似吃碰槓待俯視確認", s5)
    all_events += show("6. 辨識出錯 → 標記異常、需人工複查，但不丟資料", s6)

    # 把事件流輸出成 JSONL（一動作一行）—— 這就是之前討論的即時寫入格式
    out = "事件流範例.jsonl"
    with open(out, "w", encoding="utf-8") as f:
        for ev in all_events:
            f.write(json.dumps(ev, ensure_ascii=False) + "\n")

    print("\n" + "=" * 56)
    print(f"已輸出事件流範例：{out}")
    print("（一動作一行的 JSONL，就是之前說的即時寫入格式）")
    print("=" * 56)
